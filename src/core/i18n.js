  function resolve(setting, browserLang) {
    if (setting === 'ar' || setting === 'en') return setting;
    let b = browserLang;
    if (!b && typeof chrome !== 'undefined' && chrome.i18n && chrome.i18n.getUILanguage) b = chrome.i18n.getUILanguage();
    if (!b && typeof navigator !== 'undefined') b = navigator.language;
    return /^ar\b/i.test(b || '') ? 'ar' : 'en';
  }

  function numberFormat(lang) {
    return new Intl.NumberFormat(lang === 'ar' ? 'ar-u-nu-latn' : 'en');
  }

  function fmt(lang, n) {
    return numberFormat(lang).format(n);
  }

  function t(lang, key, vars) {
    const table = STRINGS[lang] || STRINGS.en;
    let s = table[key] !== undefined ? table[key] : STRINGS.en[key];
    if (s === undefined) return key;
    if (typeof s === 'object') {
      const n = vars && typeof vars.n === 'number' ? vars.n : 0;
      const cat = new Intl.PluralRules(lang === 'ar' ? 'ar' : 'en').select(n);
      s = s[cat] !== undefined ? s[cat] : s.other;
    }
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, (m, k) => {
        if (vars[k] === undefined) return m;
        if (typeof vars[k] === 'number') return fmt(lang, vars[k]);
        const v = String(vars[k]);
        // Keep Latin runs such as "⌃ Control + Q" or a hostname intact inside Arabic text.
        return lang === 'ar' && /[A-Za-z⌃⌘⌥⇧]/.test(v) ? '\u2068' + v + '\u2069' : v;
      });
    }
    return s;
  }

  function dir(lang) {
    return lang === 'ar' ? 'rtl' : 'ltr';
  }

  // Fills [data-i18n], [data-i18n-placeholder|title|aria-label] inside `root`.
  // `vars` provides values for placeholders such as {shortcut}.
  function apply(rootEl, lang, vars) {
    const doc = rootEl.ownerDocument || rootEl;
    if (doc.documentElement && rootEl === doc) {
      doc.documentElement.lang = lang;
      doc.documentElement.dir = dir(lang);
    }
    rootEl.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(lang, el.getAttribute('data-i18n'), vars);
    });
    for (const attr of ['placeholder', 'title', 'aria-label']) {
      rootEl.querySelectorAll(`[data-i18n-${attr}]`).forEach((el) => {
        el.setAttribute(attr, t(lang, el.getAttribute(`data-i18n-${attr}`), vars));
      });
    }
  }

  return { STRINGS, resolve, t, fmt, dir, apply };
